// Isolated guest adventure: phase visibility preserves rounds; local audio uses a bounded file.
import assert from 'node:assert/strict';
import { createRoomSnapshot, normalizeRoomSnapshot } from '../src/core/room.js';
const { chromium } = await import(process.env.MYOWNDEX_PLAYWRIGHT_MODULE || 'playwright');
const baseUrl = process.env.MYOWNDEX_SMOKE_URL || 'http://localhost:3001';
const proxy = process.env.MYOWNDEX_BROWSER_PROXY || process.env.HTTPS_PROXY || process.env.HTTP_PROXY;
const browser = await chromium.launch({ headless: true, executablePath: process.env.MYOWNDEX_BROWSER_EXECUTABLE || undefined, args: ['--no-sandbox'], ...(proxy ? { proxy: { server: proxy, bypass: 'localhost,127.0.0.1,::1' } } : {}) });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
const page = await context.newPage();
const errors = [], checks = [], remoteRoomRequests = [];
page.on('pageerror', error => errors.push(error.message));
const token = (id, name, speciesId, side, x, y) => ({ id, name, speciesId, speciesName: name.toLowerCase(), sprite: `/sprites/${speciesId}.png`, side, x, y, level: 20, currentHp: 20, maxHp: 20, stats: { hp: 20, attack: 5, defense: 5, 'special-attack': 5, 'special-defense': 5, speed: 5 }, types: ['normal'], moves: ['', '', '', ''], pp: [null, null, null, null] });
const seed = normalizeRoomSnapshot({ ...createRoomSnapshot('Nossa cena'), phase: 'batalha', hitKillProtectionUsed: ['token:little'], tokens: [token('little', 'Caterpie', 10, 'ally', 25, 75), token('large', 'Onix', 95, 'opponent', 75, 25)] });
await context.route('**/api/rooms/**', route => { remoteRoomRequests.push(`${route.request().method()} ${new URL(route.request().url()).pathname}`); return route.abort(); });
await context.route('https://pokeapi.co/api/v2/**', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ id: 1, name: 'bulbasaur', abilities: [], moves: [], stats: [], types: [{ type: { name: 'grass' } }], sprites: {}, species: { name: 'bulbasaur' }, flavor_text_entries: [] }) }));
await context.addInitScript(seed => {
    if (localStorage.getItem('adventure-scene-seeded')) return;
    localStorage.setItem('adventure-scene-seeded', '1');
    localStorage.setItem('myowndex_live_room_v1', JSON.stringify({ code: 'LOCAL', key: 'local-scene-qa', role: 'narrator', displayName: 'Narrador', local: true }));
    localStorage.setItem('myowndex_local_room_v1', JSON.stringify({ code: 'LOCAL', title: seed.title, revision: 0, updatedAt: new Date().toISOString(), snapshot: seed, players: [], events: [], media: [] }));
}, seed);
const combat = page.locator('.room-tools > .room-tool > summary').filter({ hasText: /^Resolver um movimento$/ });
const capture = page.locator('.room-tools > .room-tool > summary').filter({ hasText: /^Captura$/ });
const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('myowndex_local_room_v1')).snapshot);
const phase = async id => { await page.locator(`.room-phase-options [data-phase='${id}']`).click(); await page.waitForFunction(id => JSON.parse(localStorage.getItem('myowndex_local_room_v1')).snapshot.phase === id, id); };
const pane = async name => { const nav = page.locator('.room-mobile-nav'); if (await nav.isVisible()) await nav.getByRole('button', { name, exact: true }).click(); };
const fit = async label => {
    const metrics = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth, outside: [...document.querySelectorAll('.room-app button,.room-app select,.room-app input,.room-app textarea,.room-app summary')].filter(e => { const r=e.getBoundingClientRect(); return r.width && r.height && e.getClientRects().length && (r.left<-.5 || r.right>innerWidth+.5); }).map(e => e.getAttribute('aria-label') || e.textContent.slice(0,60)) }));
    assert.equal(metrics.scroll, metrics.width, label); assert.deepEqual(metrics.outside, [], label); checks.push(label);
};
try {
    await page.goto(baseUrl, { waitUntil: 'domcontentloaded' });
    await page.getByRole('button', { name: 'Abrir a Central da Aventura', exact: true }).click();
    await page.locator('.room-app').waitFor();
    await pane('Campo');
    assert.equal(await combat.count(), 1);
    assert.equal(await capture.count(), 1);
    await page.locator('.turn-order').getByRole('button', { name: 'Rolar iniciativa', exact: true }).click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('myowndex_local_room_v1')).snapshot.initiative.length === 2);
    const initial = await state();
    await phase('exploracao');
    assert.equal(await page.locator('.turn-order').count(), 0);
    assert.equal(await combat.count(), 0);
    assert.equal(await capture.count(), 1);
    assert.equal(await page.locator('.battlefield-side-label').count(), 0);
    assert.deepEqual((await state()).initiative, initial.initiative);
    checks.push('Exploration keeps the scene and preserves the active round without battle controls');
    await phase('interpretacao');
    assert.equal(await page.locator('.battlefield-board').count(), 0);
    assert.equal(await capture.count(), 0);
    assert.equal(await combat.count(), 0);
    assert.equal(await page.locator('.room-notes-panel').evaluate(e => e.open), true);
    checks.push('Interpretation shows notes and a compact scene instead of a battle');
    await phase('intervalo');
    assert.equal(await combat.count(), 0);
    assert.equal(await capture.count(), 0);
    assert.equal(await page.locator('.battlefield-board').count(), 0);
    assert.equal(await page.locator('.turn-order').count(), 0);
    await page.getByRole('button', { name: 'Cuidar de Onix', exact: true }).click();
    assert.equal(await page.locator('.token-inspector').count(), 1);
    checks.push('Interval hides combat and initiative and keeps Pokémon care directly available');
    await phase('batalha');
    assert.equal(await combat.count(), 1);
    assert.equal(await capture.count(), 1);
    assert.deepEqual((await state()).initiative, initial.initiative);
    assert.deepEqual((await state()).hitKillProtectionUsed, initial.hitKillProtectionUsed, 'Returning to an active battle must not restore protection');
    const little = page.locator('.room-token[aria-label^="Caterpie,"]');
    await little.click();
    const selected = await state();
    assert.equal(selected.tokens.find(t => t.id === 'little').x, 25);
    assert.equal(selected.tokens.find(t => t.id === 'little').y, 75);
    assert.equal(await page.locator('.battlefield-focus').count(), 1);
    assert.equal(await page.locator('.room-token-status-card').count(), 0);
    checks.push('Selecting a Pokémon leaves coordinates unchanged and docks its readable HUD below the field');
    const sizes = await page.locator('.room-token .pokemon-sized-sprite').evaluateAll(frames => frames.map(frame => ({ heightDm: Number(frame.dataset.pokemonHeightDm), scale: Number(frame.dataset.pokemonScale), height: frame.getBoundingClientRect().height })));
    const caterpie = sizes.find(frame => frame.heightDm === 3), onix = sizes.find(frame => frame.heightDm === 88);
    assert.ok(Math.abs(caterpie.scale / onix.scale - 3 / 88) < 1e-8);
    assert.ok(Math.abs(caterpie.height / onix.height - 3 / 88) < 1e-6);
    assert.equal(await page.locator('.battlefield-party-strip button').count(), 2);
    checks.push('Dex heights keep Caterpie visually smaller than Onix while retaining large targets');
    for (const theme of ['normal', 'night']) for (const width of [320,390,768,1280]) {
        await page.setViewportSize({ width, height: 844 });
        await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
        await pane('Campo'); await fit(`Scene fits ${width} ${theme}`);
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.emulateMedia({ reducedMotion: 'reduce' });await pane('Campo');
    await little.scrollIntoViewIfNeeded();
    await page.waitForFunction(() => document.querySelector('.room-token[aria-label^="Caterpie,"] .pokemon-sized-sprite')?.dataset.pokemonMotion === 'static');
    assert.equal(await page.locator('.room-token img').first().evaluate(e => getComputedStyle(e).animationName), 'none');
    checks.push('Reduced motion uses the same identity without animated frames');
    await page.locator('.battlefield-card').screenshot({ path: '/tmp/myowndex-adventure-field-390.png' });
    assert.deepEqual(remoteRoomRequests, [], 'The isolated local adventure never creates or edits remote rooms');
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ count: checks.length, checks, errors, remoteRoomRequests }, null, 2));
} finally { await browser.close(); }
