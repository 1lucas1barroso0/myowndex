    await page.getByRole('alertdialog', { name: 'Remover esta trilha?', exact: true }).getByRole('button', { name: 'Remover trilha', exact: true }).click();
    await page.locator('.audio-now').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('.audio-tool audio').getAttribute('src'), null);
    checks.push('Local music can be completely removed');
    await page.locator('.audio-effects > summary').click();
    await page.locator('.audio-tool').getByRole('button', { name: 'Tocar Cura', exact: true }).click();
