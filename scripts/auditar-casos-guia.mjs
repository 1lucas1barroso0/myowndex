import { writeFile, readFile } from 'node:fs/promises';
import { reproduceGuideCases } from '../src/core/guideAuditFixtures.js';
const file=new URL('../src/data/guide-audit-cases.js',import.meta.url);
const content='// Generated by scripts/auditar-casos-guia.mjs; verified against the game engine.\nexport const GUIDE_AUDIT_CASES = '+JSON.stringify(reproduceGuideCases(),null,2)+';\n';
if(process.argv.includes('--write'))await writeFile(file,content);
else if(await readFile(file,'utf8')!==content)throw Error('Os casos mostrados no Guia diferem da execução do núcleo.');
console.log('Casos do Guia reproduzidos: dados, dano, sono, veneno, XP, Max, captura, descanso, grupo e fuga.');
